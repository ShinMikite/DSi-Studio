"""Convert the included public-domain X11 font to Studio's 6x11 cells."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT/'assets/fonts/6x10.bdf').read_text(encoding='utf-8')
glyphs = {}
for block in source.split('STARTCHAR ')[1:]:
    lines = block.split('ENDCHAR', 1)[0].splitlines()
    encoding = int(next(line.split()[1] for line in lines if line.startswith('ENCODING ')))
    if not 32 <= encoding <= 126:
        continue
    assert 'BBX 6 10 0 -2' in lines and 'DWIDTH 6 0' in lines
    start = lines.index('BITMAP') + 1
    bitmap = lines[start:start+10]
    assert len(bitmap) == 10 and all(len(row) == 2 for row in bitmap)
    # BDF stores the leftmost pixel in the high bit. Studio uses the low bit.
    rows = [0] + [sum((1 << x) for x in range(6) if int(row, 16) & (128 >> x)) for row in bitmap]
    glyphs[encoding] = '{' + ','.join(str(row) for row in rows) + '}'

assert set(glyphs) == set(range(32, 127))
header = ('// Public domain X11 misc-fixed 6x10 glyphs; see licenses/x11-fixed.txt.\n'
          '// Generated by tools/make_font.py with one row of top padding.\n'
          'static const unsigned char font[95][11] = {\n')
(ROOT/'common/font.h').write_text(header + ',\n'.join(glyphs[n] for n in range(32, 127)) + '\n};\n', encoding='utf-8')
print('Generated 95 ASCII glyphs from the included X11 font; no system font is required.')
