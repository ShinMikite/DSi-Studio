"""Generate the small bitmap UI font; no runtime font dependency."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype('C:/Windows/Fonts/consola.ttf', 10)
rows=[]
for ch in range(32,127):
    im=Image.new('1',(6,11)); ImageDraw.Draw(im).text((0,-1),chr(ch),font=font,fill=1)
    rows.append('{'+','.join(str(sum((1<<x) if im.getpixel((x,y)) else 0 for x in range(6))) for y in range(11))+'}')
(root/'common/font.h').write_text('// Generated by tools/make_font.py\nstatic const unsigned char font[95][11] = {\n'+',\n'.join(rows)+'\n};\n')
